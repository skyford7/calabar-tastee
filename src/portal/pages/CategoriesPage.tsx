import { useState, type FormEvent } from "react";
import { useMutation, useQueryClient } from "@tanstack/react-query";
import { toast } from "sonner";
import { Eye, EyeOff, Pencil, Plus, Trash2 } from "lucide-react";
import { errorMessage, supabase } from "@/lib/supabase";
import { qk, useCategories, useMenuItems } from "@/lib/queries";
import type { Category } from "@/lib/types";
import {
  Badge,
  Button,
  Checkbox,
  EmptyState,
  ErrorBlock,
  Field,
  Input,
  LoadingBlock,
  Modal,
  PageHeader,
  Table,
  Textarea,
  useConfirm,
} from "../ui";

type Draft = {
  id?: number;
  name: string;
  description: string;
  sort_order: number;
  is_visible: boolean;
};

export function CategoriesPage() {
  const qc = useQueryClient();
  const confirm = useConfirm();
  const cats = useCategories();
  const menu = useMenuItems();
  const [draft, setDraft] = useState<Draft | null>(null);

  const counts = new Map<number, number>();
  (menu.data ?? []).forEach(i =>
    counts.set(i.category_id, (counts.get(i.category_id) ?? 0) + 1)
  );

  const refresh = () =>
    Promise.all([
      qc.invalidateQueries({ queryKey: qk.categories }),
      qc.invalidateQueries({ queryKey: qk.menu }),
    ]);

  const save = useMutation({
    mutationFn: async (d: Draft) => {
      const row = {
        name: d.name.trim(),
        description: d.description.trim() || null,
        sort_order: d.sort_order,
        is_visible: d.is_visible,
      };
      const { error } = d.id
        ? await supabase.from("categories").update(row).eq("id", d.id)
        : await supabase.from("categories").insert({ ...row, slug: "" }); // slug generated by DB trigger
      if (error) throw error;
    },
    onSuccess: (_r, d) => {
      toast.success(d.id ? "Category updated" : "Category added");
      setDraft(null);
      void refresh();
    },
    onError: e => toast.error(errorMessage(e)),
  });

  const toggle = useMutation({
    mutationFn: async (c: Category) => {
      const { error } = await supabase
        .from("categories")
        .update({ is_visible: !c.is_visible })
        .eq("id", c.id);
      if (error) throw error;
    },
    onSuccess: () => void refresh(),
    onError: e => toast.error(errorMessage(e)),
  });

  const remove = useMutation({
    mutationFn: async (c: Category) => {
      const { error } = await supabase
        .from("categories")
        .delete()
        .eq("id", c.id);
      if (error) throw error;
    },
    onSuccess: () => {
      toast.success("Category deleted");
      void refresh();
    },
    onError: e => toast.error(errorMessage(e)),
  });

  const onDelete = async (c: Category) => {
    const n = counts.get(c.id) ?? 0;
    if (n > 0) {
      toast.error(
        `Move or delete the ${n} item${n === 1 ? "" : "s"} in “${c.name}” first.`
      );
      return;
    }
    if (
      await confirm({
        title: "Delete category?",
        message: `“${c.name}” will be deleted.`,
        confirmLabel: "Delete",
        danger: true,
      })
    ) {
      remove.mutate(c);
    }
  };

  const submit = (e: FormEvent) => {
    e.preventDefault();
    if (draft) save.mutate(draft);
  };

  const nextOrder =
    Math.max(0, ...(cats.data ?? []).map(c => c.sort_order)) + 10;

  return (
    <>
      <PageHeader
        title="Categories"
        description="Sections of the menu, in the order shown on the website. Hidden categories hide all their dishes."
        actions={
          <Button
            onClick={() =>
              setDraft({
                name: "",
                description: "",
                sort_order: nextOrder,
                is_visible: true,
              })
            }
          >
            <Plus className="h-4 w-4" /> Add category
          </Button>
        }
      />

      {cats.error ? (
        <ErrorBlock error={cats.error} />
      ) : cats.isLoading ? (
        <LoadingBlock />
      ) : !cats.data?.length ? (
        <EmptyState title="No categories yet." />
      ) : (
        <Table
          head={
            <tr>
              <th className="px-4 py-3">Order</th>
              <th className="px-4 py-3">Name</th>
              <th className="px-4 py-3">Dishes</th>
              <th className="px-4 py-3">Status</th>
              <th className="px-4 py-3 text-right">Actions</th>
            </tr>
          }
        >
          {cats.data.map(c => (
            <tr key={c.id} className="text-amber-100/80">
              <td className="px-4 py-3 text-amber-100/50">{c.sort_order}</td>
              <td className="px-4 py-3">
                <div className="font-medium text-white">{c.name}</div>
                {c.description && (
                  <div className="text-xs text-amber-100/40">
                    {c.description}
                  </div>
                )}
              </td>
              <td className="px-4 py-3">{counts.get(c.id) ?? 0}</td>
              <td className="px-4 py-3">
                {c.is_visible ? (
                  <Badge tone="green">Visible</Badge>
                ) : (
                  <Badge>Hidden</Badge>
                )}
              </td>
              <td className="px-4 py-3">
                <div className="flex justify-end gap-1">
                  <Button
                    size="sm"
                    variant="ghost"
                    title={c.is_visible ? "Hide" : "Show"}
                    onClick={() => toggle.mutate(c)}
                  >
                    {c.is_visible ? (
                      <Eye className="h-4 w-4" />
                    ) : (
                      <EyeOff className="h-4 w-4" />
                    )}
                  </Button>
                  <Button
                    size="sm"
                    variant="ghost"
                    title="Edit"
                    onClick={() =>
                      setDraft({
                        id: c.id,
                        name: c.name,
                        description: c.description ?? "",
                        sort_order: c.sort_order,
                        is_visible: c.is_visible,
                      })
                    }
                  >
                    <Pencil className="h-4 w-4" />
                  </Button>
                  <Button
                    size="sm"
                    variant="ghost"
                    title="Delete"
                    className="text-red-400"
                    onClick={() => void onDelete(c)}
                  >
                    <Trash2 className="h-4 w-4" />
                  </Button>
                </div>
              </td>
            </tr>
          ))}
        </Table>
      )}

      <Modal
        open={!!draft}
        onClose={() => setDraft(null)}
        title={draft?.id ? "Edit category" : "New category"}
        footer={
          <>
            <Button variant="ghost" onClick={() => setDraft(null)}>
              Cancel
            </Button>
            <Button type="submit" form="category-form" loading={save.isPending}>
              Save
            </Button>
          </>
        }
      >
        {draft && (
          <form id="category-form" onSubmit={submit} className="space-y-4">
            <Field label="Name">
              <Input
                required
                maxLength={80}
                value={draft.name}
                onChange={e => setDraft({ ...draft, name: e.target.value })}
              />
            </Field>
            <Field label="Description" hint="Optional">
              <Textarea
                rows={2}
                maxLength={500}
                value={draft.description}
                onChange={e =>
                  setDraft({ ...draft, description: e.target.value })
                }
              />
            </Field>
            <Field label="Sort order" hint="Lower numbers show first">
              <Input
                type="number"
                value={draft.sort_order}
                onChange={e =>
                  setDraft({ ...draft, sort_order: Number(e.target.value) })
                }
              />
            </Field>
            <Checkbox
              label="Visible on website"
              checked={draft.is_visible}
              onChange={v => setDraft({ ...draft, is_visible: v })}
            />
          </form>
        )}
      </Modal>
    </>
  );
}
